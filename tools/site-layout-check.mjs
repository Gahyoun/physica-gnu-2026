// Responsive GNU/KRDS shell and TOC checks. Does not renew earlier physics/model evidence.
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const {chromium}=require(process.env.PHYSICA_PLAYWRIGHT||'playwright');
const base=process.env.PHYSICA_BASE_URL||'http://127.0.0.1:8775/';
const browser=await chromium.launch({headless:true,...(process.env.PHYSICA_BROWSER_CHANNEL?{channel:process.env.PHYSICA_BROWSER_CHANNEL}:{})});
const report={date:new Date().toISOString(),base,widths:[320,390,768,1360,1440],checks:[],errors:[],scope:'Shared navigation and homepage information layout; no new numerical-model or full-book evidence.'};
const pass=name=>report.checks.push(name);
try{
 const context=await browser.newContext({viewport:{width:1440,height:1100},colorScheme:'light',reducedMotion:'reduce'});
 const page=await context.newPage();
 page.on('pageerror',error=>report.errors.push(error.message));
 const home=new URL('index.html',base).href;
 for(const width of report.widths){
  await page.setViewportSize({width,height:1100});
  await page.goto(home,{waitUntil:'networkidle'});await page.evaluate(()=>document.fonts.ready);
  assert.equal(await page.locator('#book-navigation').count(),0,'Homepage has no duplicate sidebar');
  assert.equal(await page.locator('.menu-toggle').count(),0,'Homepage has no empty menu button');
  assert.equal(await page.locator('.toc-chapter').count(),7);
  assert.equal(await page.locator('.toc-pages a').count(),566);
  assert.equal(await page.locator('.toc-tree details[open]').count(),0,'All chapters start with the same closed state');
  assert.ok((await page.locator('.toc-overview').innerText()).includes('7개 단원 · 149개 주제 · 566쪽'));
  assert.ok(await page.getByLabel('이 웹교재에서 찾을 내용',{exact:true}).isVisible());
  assert.equal(await page.locator('.home-search').getAttribute('method'),'get');
  assert.equal(await page.locator('.home-search').getAttribute('action'),'search.html');
  for(const text of ['웹교재 목차','자료종류별','사이트 안내'])assert.ok(await page.locator('.top-menu').getByRole('link',{name:text,exact:true}).isVisible());
  for(const value of ['light','dark'])assert.ok(await page.locator(`.header-inner [data-theme-value=${value}]`).isVisible());
  await page.locator('.search-menu>summary').click();
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'Open search menu stays in viewport at '+width);
  await page.keyboard.press('Escape');
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'No page overflow at '+width);
  const rows=await page.locator('.toc-chapter>summary').evaluateAll(nodes=>nodes.map(node=>{
   const label=node.querySelector('.toc-label').getBoundingClientRect(),count=node.querySelector('.toc-count').getBoundingClientRect(),mark=node.querySelector('.toc-disclosure').getBoundingClientRect();
   return {labelWidth:label.width,countLeft:count.left,labelRight:label.right,markLeft:mark.left,countRight:count.right};
  }));
  assert.ok(rows.every(row=>row.labelWidth>0&&row.countLeft>=row.labelRight&&row.markLeft>=row.countRight),'Chapter names, page counts and controls occupy separate columns at '+width);
  pass('Homepage columns, navigation, search and no overflow at '+width+'px');
 }
 await page.setViewportSize({width:1440,height:1100});
 await page.getByRole('button',{name:'모두 전개하기',exact:true}).click();
 assert.equal(await page.locator('.toc-tree details:not([open])').count(),0);
 await page.getByRole('button',{name:'모두 감추기',exact:true}).click();
 assert.equal(await page.locator('.toc-tree details[open]').count(),0);
 const summary=page.locator('#chapter-1>summary');await summary.focus();await page.keyboard.press('Enter');
 assert.equal(await page.locator('#chapter-1').getAttribute('open'),'');
 await page.locator('#chapter-1 .toc-section>summary').first().click();
 await page.locator('#chapter-1 .toc-pages a').first().click();
 await page.waitForURL('**/lesson-1-1-1-1.html');
 assert.ok((await page.locator('h1').innerText()).includes('운동량'));
 assert.ok(await page.locator('math').count()>0,'Textbook math is preserved');
 assert.equal(await page.locator('.book-nav .nav-tools a').count(),2,'Only distinct animation entry points are repeated in the sidebar');
 pass('Native disclosure keyboard control, all expand/collapse and existing lesson destination');
 await page.setViewportSize({width:320,height:1100});
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
 await page.getByRole('button',{name:'목차',exact:true}).click();
 assert.equal(await page.locator('.menu-toggle').getAttribute('aria-expanded'),'true');
 assert.ok(await page.locator('#book-navigation').isVisible());
 await page.keyboard.press('Escape');
 assert.equal(await page.locator('.menu-toggle').getAttribute('aria-expanded'),'false');
 assert.equal(await page.evaluate(()=>document.activeElement.className),'menu-toggle');
 pass('Textbook mobile sidebar opens, closes with Escape and restores focus');
 await page.goto(new URL('index.html#chapter-6',base).href,{waitUntil:'networkidle'});
 assert.equal(await page.locator('#chapter-6').getAttribute('open'),'');
 await page.locator('.search-menu>summary').click();
 assert.ok(await page.locator('.search-menu a[href="search.html"]').isVisible());
 await page.keyboard.press('Escape');assert.equal(await page.locator('.search-menu').getAttribute('open'),null);
 pass('Existing chapter anchors and header search dropdown');
 await page.locator('#home-query').fill('질량중심');
 await page.locator('.home-search button[type=submit]').click();
 await page.waitForURL('**/search.html?q=*');
 await page.waitForFunction(()=>document.querySelector('[data-search-results]')?.children.length>0);
 assert.equal(new URL(page.url()).searchParams.get('q'),'질량중심');
 assert.ok((await page.locator('[data-search-results]').innerText()).includes('질량중심'));
 pass('Home GET form reaches real shared search results');
 await page.goto(home,{waitUntil:'networkidle'});
 await page.locator('.header-inner [data-theme-value=dark]').click();await page.reload({waitUntil:'networkidle'});
 assert.equal(await page.locator('html').getAttribute('data-theme'),'dark');
 assert.equal(await page.locator('.header-inner [data-theme-value=dark]').getAttribute('aria-pressed'),'true');
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
 await page.emulateMedia({media:'print'});
 assert.equal(await page.locator('body').evaluate(node=>getComputedStyle(node).backgroundColor),'rgb(255, 255, 255)');
 assert.ok(await page.locator('.home-search').isHidden());
 await page.emulateMedia({media:'screen'});
 await page.locator('.header-inner [data-theme-value=light]').click();
 pass('Persisted dark/light controls and light print layout');
 await page.setViewportSize({width:1440,height:1100});
 await page.evaluate(()=>document.body.style.zoom='2');
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'200% zoom homepage overflow');
 await page.evaluate(()=>document.body.style.zoom='1');
 await page.reload({waitUntil:'networkidle'});await page.keyboard.press('Tab');
 assert.equal(await page.evaluate(()=>document.activeElement.textContent),'본문 바로가기');
 await page.keyboard.press('Enter');assert.equal(await page.evaluate(()=>document.activeElement.id),'main');
 pass('200% zoom and keyboard skip link');
 const staticContext=await browser.newContext({javaScriptEnabled:false,viewport:{width:390,height:844}});
 const staticPage=await staticContext.newPage();await staticPage.goto(home);
 await staticPage.locator('#chapter-1>summary').click();assert.equal(await staticPage.locator('#chapter-1').getAttribute('open'),'');
 assert.equal(await staticPage.locator('.toc-pages a').count(),566);
 await staticPage.goto(new URL('lesson-1-1-1-1.html',base).href);
 assert.ok(await staticPage.locator('math').count()>0);
 await staticContext.close();
 pass('No-JavaScript native TOC and readable textbook math');
 assert.deepEqual(report.errors,[]);report.passed=true;
 if(process.env.PHYSICA_LAYOUT_REPORT)await fs.writeFile(process.env.PHYSICA_LAYOUT_REPORT,JSON.stringify(report,null,2)+'\n');
 console.log(JSON.stringify(report,null,2));
 await context.close();
}finally{await browser.close();}
